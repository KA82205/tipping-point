import os
root=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..')
FC=json.load(open(os.path.join(root,'pipeline','forecast_2024_figA2.json')))
rows=[]
for line in csv.splitlines():
    n,a,ev,d,r,cat=line.split(','); d=int(d); r=int(r)
    f=FC[a]
    rows.append(dict(name=n,abbr=a,ev=int(ev),dem=d,rep=r,rating=cat,share=round(100*d/(d+r),2),fc=f['mean'],lo=f['lo'],hi=f['hi'],pDem=f['pDem']))
# EV check
fr=sum(x['ev'] for x in rows if x['rating'].endswith('R'))
ar=sum(x['ev'] for x in rows if x['rep']>x['dem'])
ok=sum((x['rating'].endswith('D'))==(x['dem']>x['rep']) for x in rows)
statewide=[x for x in rows if x['abbr'] not in('ME1','ME2','NE1','NE2','NE3')]
D=sum(x['dem'] for x in statewide);R=sum(x['rep'] for x in statewide)
print('forecast R EV',fr,'actual R EV',ar,'correct',ok,'/',len(rows),'nat dem 2p',100*D/(D+R))
json.dump({r['abbr']:{'name':r['name'],'ev':r['ev'],'share':r['share'],'votes':r['dem']+r['rep']} for r in rows},open(os.path.join(root,'pipeline','results_2024.json'),'w'),indent=1)
